export function getSubjectsForGrade(g) {
  if (g <= 4) return SUBJECTS['1-4'];
  if (g <= 9) return SUBJECTS['5-9'];
  return SUBJECTS['10-11'];
}

export const FREE_TOPIC_LIMIT = 30;

let cachedTopics = null;

export function getAllTopics() {
  if (cachedTopics) return cachedTopics;
  cachedTopics = allTopics.map(t => ({
    id: t.id,
    title: t.title,
    subject: t.subject,
    icon: SUBJECT_ICONS[t.subject] || '📘',
    grade: t.class || 5,
    short: t.short || '',
    theory: t.theory || '',
    formulas: [],
    problems: (t.problems || []).map(p => ({
      q: p.q,
      hint: p.hint || '',
      solution: p.answer || p.solution || ''
    }))
  }));
  return cachedTopics;
}

export function isTopicLocked(id, isPrem) {
  if (isPrem) return false;
  return getAllTopics().findIndex(t => t.id === id) >= FREE_TOPIC_LIMIT;
}